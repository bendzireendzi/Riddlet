function mulberry32(a: number) {
  return function () {
    let t = (a += 0x6d2b79f5);
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function hashDateString(str: string): number {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    const char = str.charCodeAt(i);
    hash = (hash << 5) - hash + char;
    hash |= 0;
  }
  return Math.abs(hash) + 12345;
}

export function getDayNumber(dateStr: string): number {
  const base = new Date('2026-01-01T00:00:00Z').getTime();
  const current = new Date(`${dateStr}T00:00:00Z`).getTime();
  const diffDays = Math.floor((current - base) / (1000 * 60 * 60 * 24));
  return Math.max(1, diffDays + 1);
}

export function getDailyRiddles(dateStr: string): Riddle[] {
  const seed = hashDateString(dateStr);
  const random = mulberry32(seed);

  const pool = [...RIDDLES_BANK];
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }

  return pool.slice(0, 7);
}

export function getRandomRiddles(count = 7, excludeIds: string[] = []): Riddle[] {
  const pool = RIDDLES_BANK.filter((r) => !excludeIds.includes(r.id));
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}
